# 4. Callback Dinámico
@app.callback(
    [Output('trend-chart', 'figure'),
     Output('kpi-units', 'children'),
     Output('bar-chart', 'figure'),
     Output('network-chart', 'figure'),
     Output('data-table', 'data')],
    [Input('filter-prov', 'value'),
     Input('filter-year', 'value'),
     Input('filter-month', 'value')]
)
def update_metrics(selected_prov, selected_year, selected_month):
    dff = df.copy()

    # Aplicar Filtro de Proveedor
    if selected_prov != 'Todos':
        dff = dff[dff['Proveedor'] == selected_prov]

    # 1. Generar Gráfico de Tendencia según los Filtros seleccionados
    if selected_year == 'Todos':
        # Mostrar tendencia año tras año
        trend_df = dff.groupby('Year')['Unidades_Enviadas'].sum().reset_index()
        fig_trend = px.area(trend_df, x='Year', y='Unidades_Enviadas', markers=True, text='Unidades_Enviadas')
        fig_trend.update_xaxes(dtick=1)
    else:
        # Mostrar tendencia mes a mes dentro del año seleccionado
        dff_trend_year = dff[dff['Year'] == selected_year]
        trend_df = dff_trend_year.groupby('Mes')['Unidades_Enviadas'].sum().reindex(months_order).reset_index()
        fig_trend = px.line(trend_df, x='Mes', y='Unidades_Enviadas', markers=True, text='Unidades_Enviadas')

    fig_trend.update_traces(
        line_color='#00fff5',
        fillcolor='rgba(0, 255, 245, 0.15)' if selected_year == 'Todos' else None,
        textposition='top center',
        texttemplate='%{text:,.0f}'
    )
    fig_trend.update_layout(
        paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)',
        font=dict(color='white', size=11),
        xaxis=dict(showgrid=True, gridcolor='#16213e'),
        yaxis=dict(showgrid=True, gridcolor='#16213e', title="Unidades Totales"),
        margin=dict(l=20, r=20, t=10, b=20),
        height=220
    )

    # Aplicar Filtros Secundarios de Año y Mes al resto de componentes
    dff_filtered = dff.copy()
    if selected_year != 'Todos':
        dff_filtered = dff_filtered[dff_filtered['Year'] == selected_year]
    if selected_month != 'Todos':
        dff_filtered = dff_filtered[dff_filtered['Mes'] == selected_month]

    # 2. KPI Total
    total_unidades = f"{dff_filtered['Unidades_Enviadas'].sum():,}"

    # 3. Bar Chart por Proveedor
    prov_summary = dff_filtered.groupby('Proveedor')['Unidades_Enviadas'].sum().reset_index().sort_values(by='Unidades_Enviadas', ascending=True)
    fig_bar = px.bar(prov_summary, x='Unidades_Enviadas', y='Proveedor', orientation='h', text='Unidades_Enviadas')
    fig_bar.update_traces(marker_color='#00fff5', textposition='outside', texttemplate='%{text:,.0f}')
    fig_bar.update_layout(
        paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)',
        font=dict(color='white', size=10),
        xaxis=dict(showgrid=False, visible=False),
        yaxis=dict(showgrid=False),
        margin=dict(l=0, r=50, t=10, b=10),
        height=300
    )

    # 4. Network/Scatter Chart por Plataforma
    fig_network = px.scatter(
        dff_filtered, x='Plataforma_Destino', y='Proveedor', size='Unidades_Enviadas',
        color='Estado_Stock', hover_name='Juego', size_max=28,
        color_discrete_map={'Abastecido': '#00ff88', 'En Tránsito': '#ffcc00', 'Crítico': '#ff4d4d'}
    )
    fig_network.update_layout(
        paper_bgcolor='rgba(0,0,0,0)', plot_bgcolor='rgba(0,0,0,0)',
        font=dict(color='white', size=10),
        xaxis=dict(showgrid=True, gridcolor='#16213e', title="Plataforma de Destino"),
        yaxis=dict(showgrid=True, gridcolor='#16213e', title=""),
        margin=dict(l=10, r=10, t=10, b=20),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
        height=360
    )

    return fig_trend, total_unidades, fig_bar, fig_network, dff_filtered.tail(15).to_dict('records')

