import dash
from dash import dcc, html, dash_table, Input, Output
import plotly.express as px
import pandas as pd
import numpy as np

# 1. Dataset Histórico con Meses y Años (2019 - 2026)
np.random.seed(42)
years = list(range(2019, 2027))
months_order = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
proveedores = ["EveryMatrix", "Betfounders", "Elantil", "Calimaco", "IGP", "SoftGamings", "RubyPlay", "SkillOnNet", "Yggdrasil", "Pragmatic Play"]
plataformas = ["Casino LatAm", "BetGlobal", "PlayEuro", "Vegas Online", "WinMaster"]

data = []
for y in years:
    growth = 1.0 + (y - 2019) * 0.22  # Tendencia de crecimiento continuo
    for m in months_order:
        for _ in range(np.random.randint(4, 8)):
            prov = np.random.choice(proveedores)
            plat = np.random.choice(plataformas)
            units = int(np.random.randint(1200, 4800) * growth)
            estado = np.random.choice(["Abastecido", "En Tránsito", "Crítico"], p=[0.70, 0.20, 0.10])
            data.append({
                "Proveedor": prov,
                "Juego": f"{prov[:4]}_Slot_{np.random.randint(100, 999)}",
                "Plataforma_Destino": plat,
                "Unidades_Enviadas": units,
                "Estado_Stock": estado,
                "Mes": m,
                "Year": y
            })

df = pd.DataFrame(data)

